-- Run once in the dedicated Robotist project. No private data is exposed to
-- anonymous or authenticated Data API clients; access is through our server.
BEGIN;
CREATE TABLE IF NOT EXISTS applications (
  id TEXT PRIMARY KEY, name TEXT NOT NULL, email TEXT NOT NULL,
  location TEXT NOT NULL, organization TEXT NOT NULL, role TEXT NOT NULL, website TEXT NOT NULL,
  experience TEXT NOT NULL, motivation TEXT NOT NULL, consent INTEGER NOT NULL,
  public_consent INTEGER NOT NULL, status TEXT NOT NULL DEFAULT 'pending',
  notes TEXT NOT NULL DEFAULT '', version INTEGER NOT NULL DEFAULT 1,
  service_regions TEXT NOT NULL DEFAULT '', availability TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text, updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text);
CREATE UNIQUE INDEX IF NOT EXISTS applications_email_lower ON applications(lower(email));
CREATE TABLE IF NOT EXISTS profiles (
  id TEXT PRIMARY KEY, application_id TEXT UNIQUE REFERENCES applications(id), name TEXT NOT NULL,
  title TEXT NOT NULL DEFAULT '', location TEXT NOT NULL DEFAULT '', bio TEXT NOT NULL DEFAULT '',
  website TEXT NOT NULL DEFAULT '', photo TEXT NOT NULL DEFAULT '', consent INTEGER NOT NULL DEFAULT 0,
  published INTEGER NOT NULL DEFAULT 0, sort_order INTEGER NOT NULL DEFAULT 0,
  version INTEGER NOT NULL DEFAULT 1, updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text,
  academic_background TEXT NOT NULL DEFAULT '', credentials TEXT NOT NULL DEFAULT '',
  consent_proposals INTEGER NOT NULL DEFAULT 0, consent_materials INTEGER NOT NULL DEFAULT 0,
  consent_reference TEXT NOT NULL DEFAULT '', consent_date TEXT NOT NULL DEFAULT '',
  agreement_status TEXT NOT NULL DEFAULT 'not_started', agreement_reference TEXT NOT NULL DEFAULT '');
CREATE TABLE IF NOT EXISTS audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, object_id TEXT NOT NULL,
  action TEXT NOT NULL, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text);
CREATE TABLE IF NOT EXISTS rate_limits (key TEXT NOT NULL, at DOUBLE PRECISION NOT NULL);
CREATE INDEX IF NOT EXISTS rate_key ON rate_limits(key, at);
CREATE TABLE IF NOT EXISTS inquiries (
  id TEXT PRIMARY KEY, submission_token TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL, email TEXT NOT NULL, company TEXT NOT NULL DEFAULT '',
  location TEXT NOT NULL DEFAULT '', phone TEXT NOT NULL DEFAULT '', message TEXT NOT NULL,
  interest TEXT NOT NULL DEFAULT '', items TEXT NOT NULL, source TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'new', notes TEXT NOT NULL DEFAULT '', version INTEGER NOT NULL DEFAULT 1,
  details TEXT NOT NULL DEFAULT '{}', created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text,
  updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text);
CREATE INDEX IF NOT EXISTS inquiry_status ON inquiries(status, created_at);
CREATE TABLE IF NOT EXISTS catalog_products (
  id TEXT PRIMARY KEY, slug TEXT UNIQUE NOT NULL, version INTEGER NOT NULL,
  document TEXT NOT NULL, published TEXT,
  sequence BIGINT GENERATED BY DEFAULT AS IDENTITY);
CREATE TABLE IF NOT EXISTS catalog_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_id TEXT NOT NULL,
  occurred_at TEXT DEFAULT CURRENT_TIMESTAMP::text, action TEXT NOT NULL, version INTEGER NOT NULL);
ALTER TABLE applications ENABLE ROW LEVEL SECURITY;
ALTER TABLE profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE audit ENABLE ROW LEVEL SECURITY;
ALTER TABLE rate_limits ENABLE ROW LEVEL SECURITY;
ALTER TABLE inquiries ENABLE ROW LEVEL SECURITY;
ALTER TABLE catalog_products ENABLE ROW LEVEL SECURITY;
ALTER TABLE catalog_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON applications, profiles, audit, rate_limits, inquiries, catalog_products, catalog_events FROM anon, authenticated;
INSERT INTO storage.buckets (id, name, public, file_size_limit)
VALUES ('robotist-private', 'robotist-private', false, 8388608)
ON CONFLICT (id) DO NOTHING;
COMMIT;
